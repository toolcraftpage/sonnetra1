import { formatTranscriptForCopy } from "./transcript-copy.ts";

export type TranscriptExportSegment = {
  sequence_number: number;
  text: string;
  start_ms: number | null;
  end_ms: number | null;
};

export type TranscriptExportRecord = {
  id: string;
  video_id: string;
  source_url: string;
  title: string | null;
  language_code: string;
  language_name: string;
  is_auto_generated: boolean;
  provider: string;
  provider_reference: string | null;
  source_metadata: Record<string, unknown>;
  full_text: string | null;
  created_at: string;
};

export type TranscriptExportFormat = "txt" | "srt" | "vtt" | "json";

export function hasSegmentStartTimes(segments: readonly TranscriptExportSegment[]): boolean {
  if (segments.length === 0) return false;
  let previousStart = -1;

  for (const segment of segments) {
    if (segment.start_ms === null || !Number.isFinite(segment.start_ms) || segment.start_ms < 0 || segment.start_ms < previousStart) {
      return false;
    }
    previousStart = segment.start_ms;
  }

  return true;
}

export function hasValidSubtitleTiming(segments: readonly TranscriptExportSegment[]): boolean {
  if (!hasSegmentStartTimes(segments)) return false;
  let previousSequence = -1;

  for (const segment of segments) {
    if (
      !Number.isInteger(segment.sequence_number) ||
      segment.sequence_number <= previousSequence ||
      segment.end_ms === null ||
      !Number.isFinite(segment.end_ms) ||
      segment.end_ms < segment.start_ms!
    ) {
      return false;
    }
    previousSequence = segment.sequence_number;
  }

  return true;
}

export function formatTranscriptWithTimestamps(segments: readonly TranscriptExportSegment[]): string | null {
  if (!hasSegmentStartTimes(segments)) return null;
  return segments.map((segment) => `[${formatDisplayTimestamp(segment.start_ms!)}] ${segment.text}`).join("\n");
}

export function buildTranscriptExport(
  format: TranscriptExportFormat,
  transcript: TranscriptExportRecord,
  segments: readonly TranscriptExportSegment[],
): string | null {
  if (format === "txt") return formatTranscriptForCopy(transcript.full_text, segments);
  if (format === "json") {
    const fullText = typeof transcript.full_text === "string" && transcript.full_text.length > 0
      ? transcript.full_text
      : segments.map((segment) => segment.text).join("\n");

    return JSON.stringify({
      id: transcript.id,
      videoId: transcript.video_id,
      sourceUrl: transcript.source_url,
      title: transcript.title,
      language: {
        code: transcript.language_code,
        name: transcript.language_name || transcript.language_code,
        isAutoGenerated: transcript.is_auto_generated,
      },
      provider: transcript.provider,
      providerReference: transcript.provider_reference,
      sourceMetadata: transcript.source_metadata,
      createdAt: transcript.created_at,
      fullText,
      segments: segments.map((segment) => ({
        index: segment.sequence_number,
        startMs: segment.start_ms,
        endMs: segment.end_ms,
        text: segment.text,
      })),
    }, null, 2);
  }

  if (!hasValidSubtitleTiming(segments)) return null;
  if (format === "srt") return buildSrt(segments);
  return buildVtt(segments);
}

function formatDisplayTimestamp(milliseconds: number): string {
  const totalSeconds = Math.floor(milliseconds / 1000);
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;
  return hours > 0
    ? `${hours}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`
    : `${minutes}:${String(seconds).padStart(2, "0")}`;
}

function formatSubtitleTimestamp(milliseconds: number, separator: "," | "."): string {
  const hours = Math.floor(milliseconds / 3_600_000);
  const minutes = Math.floor((milliseconds % 3_600_000) / 60_000);
  const seconds = Math.floor((milliseconds % 60_000) / 1_000);
  const remainder = milliseconds % 1_000;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}${separator}${String(remainder).padStart(3, "0")}`;
}

function buildSrt(segments: readonly TranscriptExportSegment[]): string {
  return segments.map((segment, index) =>
    `${index + 1}\n${formatSubtitleTimestamp(segment.start_ms!, ",")} --> ${formatSubtitleTimestamp(segment.end_ms!, ",")}\n${segment.text}\n`,
  ).join("\n");
}

function buildVtt(segments: readonly TranscriptExportSegment[]): string {
  return ["WEBVTT", "", ...segments.map((segment, index) =>
    `${index + 1}\n${formatSubtitleTimestamp(segment.start_ms!, ".")} --> ${formatSubtitleTimestamp(segment.end_ms!, ".")}\n${segment.text}\n`,
  )].join("\n");
}