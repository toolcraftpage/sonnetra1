import type {
  RowFor,
  TableName,
} from "../../types/database.ts";

export type RepositoryContext = {
  userId: string | null;
  requestId: string;
  accessTokenHash?: string;
};

export type ListOptions = {
  limit: number;
  offset: number;
};

export interface ReadRepository<TName extends TableName> {
  getById(id: string, context: RepositoryContext): Promise<RowFor<TName> | null>;
  list(options: ListOptions, context: RepositoryContext): Promise<readonly RowFor<TName>[]>;
}

export interface TranscriptJobRepository extends ReadRepository<"transcript_jobs"> {
  create(input: TranscriptJobInsert, context: RepositoryContext): Promise<RowFor<"transcript_jobs">>;
  updateStatus(
    id: string,
    status: RowFor<"transcript_jobs">["status"],
    context: RepositoryContext,
  ): Promise<RowFor<"transcript_jobs">>;
  claimNext(staleBefore: string, context: RepositoryContext): Promise<RowFor<"transcript_jobs"> | null>;
  claimById(jobId: string, staleBefore: string, context: RepositoryContext): Promise<RowFor<"transcript_jobs"> | null>;
  complete(input: CompleteTranscriptInput, context: RepositoryContext): Promise<string>;
  fail(id: string, input: JobFailureInput, context: RepositoryContext): Promise<RowFor<"transcript_jobs">>;
  getResult(jobId: string, context: RepositoryContext): Promise<PersistedTranscript | null>;
}

export type PersistedTranscript = {
  language: { code: string; name: string; isGenerated?: boolean };
  metadata: { videoId: string; canonicalUrl: string };
  segments: readonly { index: number; text: string; startMs?: number; endMs?: number }[];
};

export type TranscriptJobInsert = Omit<RowFor<"transcript_jobs">, "id" | "created_at" | "updated_at"> & {
  id?: string;
  created_at?: string;
  updated_at?: string;
};

export type CompleteTranscriptInput = {
  jobId: string;
  videoId: string;
  sourceUrl: string;
  provider: string;
  providerReference?: string;
  languageCode: string;
  languageName: string;
  isAutoGenerated: boolean;
  fullText: string;
  segments: readonly { index: number; text: string; startMs?: number; endMs?: number }[];
};

export type JobFailureInput = {
  status: "retrying" | "failed";
  errorCode: string;
  errorMessage: string;
  nextRetryAt?: string;
  attemptCount?: number;
};

export interface TranscriptRepository extends ReadRepository<"transcripts"> {
  create(input: RowFor<"transcripts">, context: RepositoryContext): Promise<RowFor<"transcripts">>;
}

export interface TranscriptSegmentRepository {
  replaceForTranscript(
    transcriptId: string,
    segments: readonly RowFor<"transcript_segments">[],
    context: RepositoryContext,
  ): Promise<readonly RowFor<"transcript_segments">[]>;
  listForTranscript(
    transcriptId: string,
    options: ListOptions,
    context: RepositoryContext,
  ): Promise<readonly RowFor<"transcript_segments">[]>;
}

export interface SavedTranscriptRepository extends ReadRepository<"saved_transcripts"> {
  save(input: RowFor<"saved_transcripts">, context: RepositoryContext): Promise<RowFor<"saved_transcripts">>;
  remove(id: string, context: RepositoryContext): Promise<void>;
}

export interface FolderRepository extends ReadRepository<"folders"> {
  create(input: RowFor<"folders">, context: RepositoryContext): Promise<RowFor<"folders">>;
  addItem(folderId: string, savedTranscriptId: string, context: RepositoryContext): Promise<void>;
  removeItem(folderId: string, savedTranscriptId: string, context: RepositoryContext): Promise<void>;
}

export type RepositorySet = {
  jobs: TranscriptJobRepository;
  transcripts: TranscriptRepository;
  segments: TranscriptSegmentRepository;
  savedTranscripts: SavedTranscriptRepository;
  folders: FolderRepository;
};
