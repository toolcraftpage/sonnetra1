import assert from "node:assert/strict";
import test from "node:test";
import {
  buildTranscriptExport,
  formatTranscriptWithTimestamps,
  hasSegmentStartTimes,
  hasValidSubtitleTiming,
} from "../src/lib/transcript-export.ts";

const transcript = {
  id: "transcript-1",
  video_id: "video-id",
  source_url: "https://www.youtube.com/watch?v=video-id",
  title: "Source title",
  language_code: "am",
  language_name: "Amharic",
  is_auto_generated: true,
  provider: "supadata",
  provider_reference: "provider-ref-1",
  source_metadata: { source: "provider" },
  full_text: "ሰላም፣ world!\nSecond line.",
  created_at: "2026-10-08T12:00:00.000Z",
};

const segments = [
  { sequence_number: 0, text: "ሰላም፣ world!", start_ms: 0, end_ms: 1_500 },
  { sequence_number: 1, text: "Second line.", start_ms: 1_500, end_ms: 3_250 },
];

test("TXT preserves full Unicode source text and embedded line breaks", () => {
  assert.equal(buildTranscriptExport("txt", transcript, segments), transcript.full_text);
  assert.equal(buildTranscriptExport("txt", { ...transcript, full_text: null }, segments), "ሰላም፣ world!\nSecond line.");
  assert.equal(buildTranscriptExport("txt", { ...transcript, full_text: "" }, segments), "ሰላም፣ world!\nSecond line.");
});

test("JSON export falls back to segment text when the source transcript text is empty", () => {
  assert.equal(JSON.parse(buildTranscriptExport("json", { ...transcript, full_text: null }, segments)).fullText, "ሰላም፣ world!\nSecond line.");
  assert.equal(JSON.parse(buildTranscriptExport("json", { ...transcript, full_text: "" }, segments)).fullText, "ሰላም፣ world!\nSecond line.");
});

test("SRT preserves source wording and emits ordered valid timestamps", () => {
  assert.equal(
    buildTranscriptExport("srt", transcript, segments),
    "1\n00:00:00,000 --> 00:00:01,500\nሰላም፣ world!\n\n2\n00:00:01,500 --> 00:00:03,250\nSecond line.\n",
  );
});

test("VTT has a header, valid cue times, and preserved Unicode text", () => {
  assert.equal(
    buildTranscriptExport("vtt", transcript, segments),
    "WEBVTT\n\n1\n00:00:00.000 --> 00:00:01.500\nሰላም፣ world!\n\n2\n00:00:01.500 --> 00:00:03.250\nSecond line.\n",
  );
});

test("JSON preserves language, metadata, segment order, timestamps, and Unicode", () => {
  const result = JSON.parse(buildTranscriptExport("json", transcript, segments));

  assert.deepEqual(result.language, { code: "am", name: "Amharic", isAutoGenerated: true });
  assert.equal(result.provider, "supadata");
  assert.equal(result.title, "Source title");
  assert.equal(result.providerReference, "provider-ref-1");
  assert.deepEqual(result.sourceMetadata, { source: "provider" });
  assert.equal(result.fullText, transcript.full_text);
  assert.deepEqual(result.segments.map((segment) => [segment.index, segment.startMs, segment.endMs, segment.text]), [
    [0, 0, 1_500, "ሰላም፣ world!"],
    [1, 1_500, 3_250, "Second line."],
  ]);
});

test("subtitle exports and timestamped copy are unavailable when timing is missing", () => {
  const untimed = [{ sequence_number: 0, text: "No timing here", start_ms: null, end_ms: null }];

  assert.equal(hasSegmentStartTimes(untimed), false);
  assert.equal(hasValidSubtitleTiming(untimed), false);
  assert.equal(formatTranscriptWithTimestamps(untimed), null);
  assert.equal(buildTranscriptExport("srt", transcript, untimed), null);
  assert.equal(buildTranscriptExport("vtt", transcript, untimed), null);
});

test("invalid, negative, reversed, or out-of-order timestamps are rejected", () => {
  const invalidSets = [
    [{ ...segments[0], start_ms: -1 }],
    [{ ...segments[0], end_ms: -1 }],
    [{ ...segments[0], start_ms: 2_000, end_ms: 3_000 }, { ...segments[1], start_ms: 1_000, end_ms: 4_000 }],
    [{ ...segments[0], start_ms: 2_000, end_ms: 1_000 }],
    [{ ...segments[0], sequence_number: 1 }, { ...segments[1], sequence_number: 0 }],
  ];

  for (const invalid of invalidSets) {
    assert.equal(hasValidSubtitleTiming(invalid), false);
    assert.equal(buildTranscriptExport("srt", transcript, invalid), null);
    assert.equal(buildTranscriptExport("vtt", transcript, invalid), null);
  }
});

test("zero timestamps and long source segments remain intact", () => {
  const longText = `${"ቃል punctuation! ".repeat(1_000)}line\nnext`;
  const longSegments = [{ sequence_number: 0, text: longText, start_ms: 0, end_ms: 120_000 }];

  assert.equal(hasValidSubtitleTiming(longSegments), true);
  assert.equal(formatTranscriptWithTimestamps(longSegments), `[0:00] ${longText}`);
  assert.ok(buildTranscriptExport("srt", transcript, longSegments).includes(longText));
  assert.ok(buildTranscriptExport("vtt", transcript, longSegments).includes("00:02:00.000"));
});